# ---------------------------------------------------------------------------
# Orchestrator
# ---------------------------------------------------------------------------


def collect_facts() -> dict[str, Any]:
    pp = load_pyproject()
    project = pp["project"]
    return {
        "name": project["name"],
        "version": project["version"],
        "init_version": read_module_constant(INIT_PATH, "__version__"),
        "requires_python": project["requires-python"],
        "dependencies": list(project.get("dependencies", [])),
        "optional_dependencies": {
            k: list(v) for k, v in project.get("optional-dependencies", {}).items()
        },
        "scripts": dict(project.get("scripts", {})),
        "public_api": list(read_module_constant(INIT_PATH, "__all__")),
        "mcp_tools": discover_mcp_tool_names(MCP_SERVER_PATH),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Re-render to memory and diff against disk; exit 1 on drift.",
    )
    args = parser.parse_args(argv)

    facts = collect_facts()
    rendered = {
        CLAIMS_EN: render_en(facts),
        CLAIMS_KR: render_kr(facts),
    }

    if args.check:
        drift: list[str] = []
        for path, content in rendered.items():
            if not path.exists():
                drift.append(f"missing: {path.relative_to(REPO_ROOT)}")
                continue
            current = path.read_text(encoding="utf-8")
            if current != content:
                drift.append(f"stale:   {path.relative_to(REPO_ROOT)}")
        if drift:
            print("Generated claims are stale:", file=sys.stderr)
            for line in drift:
                print(f"  {line}", file=sys.stderr)
            print(
                "Regenerate with: python scripts/generate_readme_claims.py",
                file=sys.stderr,
            )
            return 1
        print("Generated claims are up to date.")
        return 0

    for path, content in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
