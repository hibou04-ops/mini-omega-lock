"""Generate ``docs/generated/claims.md`` (and ``claims_kr.md``) from source-of-truth files.

Source of truth, in order of precedence:
- ``pyproject.toml`` — distribution name, version, Python requirement,
  runtime dependencies, optional extras, console scripts.
- ``src/mini_omega_lock/__init__.py`` — ``__version__``, ``__all__``.
- ``src/mini_omega_lock/mcp/server.py`` — registered MCP tool names
  (one per ``@mcp_app.tool()`` decorator).

Run modes::

    python scripts/generate_readme_claims.py            # write files
    python scripts/generate_readme_claims.py --check    # diff-only, exit 1 on drift

The ``--check`` exit code is used in CI and ``release_audit.py`` to detect
stale generated docs. The file format starts with an AUTOGENERATED banner
so a human editor knows not to hand-edit the rendered tables.

Implementation note: no third-party imports — runs on a fresh Python 3.11
checkout before ``pip install -e`` has been run, which makes this safe to
invoke very early in CI / release-audit pipelines.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
import tomllib
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
PYPROJECT = REPO_ROOT / "pyproject.toml"
INIT_PATH = REPO_ROOT / "src" / "mini_omega_lock" / "__init__.py"
MCP_SERVER_PATH = REPO_ROOT / "src" / "mini_omega_lock" / "mcp" / "server.py"
CLAIMS_EN = REPO_ROOT / "docs" / "generated" / "claims.md"
CLAIMS_KR = REPO_ROOT / "docs" / "generated" / "claims_kr.md"


# ---------------------------------------------------------------------------
# Source-of-truth readers
# ---------------------------------------------------------------------------


def load_pyproject() -> dict[str, Any]:
    return tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))


def read_module_constant(path: Path, name: str) -> Any:
    """Pull a literal top-level assignment without importing the module."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and target.id == name:
                return ast.literal_eval(node.value)
    raise KeyError(f"{name!r} not found at module level in {path}")


def discover_mcp_tool_names(path: Path) -> list[str]:
    """Find every ``@mcp_app.tool()``-decorated function name in ``server.py``."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names: list[str] = []
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef):
            continue
        for deco in node.decorator_list:
            # Match ``@mcp_app.tool()`` (Call) and ``@mcp_app.tool`` (Attribute).
            target = deco.func if isinstance(deco, ast.Call) else deco
            if isinstance(target, ast.Attribute) and target.attr == "tool":
                value = target.value
                if isinstance(value, ast.Name) and value.id == "mcp_app":
                    names.append(node.name)
    return names


# ---------------------------------------------------------------------------
# Rendering helpers
# ---------------------------------------------------------------------------


_BANNER = (
    "<!-- AUTOGENERATED: do not edit. -->\n"
    "<!-- Source: scripts/generate_readme_claims.py -->\n"
    "<!-- Regenerate: python scripts/generate_readme_claims.py -->\n"
    "<!-- Source of truth: pyproject.toml, "
    "src/mini_omega_lock/__init__.py, "
    "src/mini_omega_lock/mcp/server.py -->\n"
)


def _bullet(items: list[str]) -> str:
    return "\n".join(f"- `{item}`" for item in items)


def _format_deps(deps: list[str]) -> str:
    return ", ".join(f"`{d}`" for d in deps)


def _format_extras(extras: dict[str, list[str]]) -> str:
    return "; ".join(f"`{name}` = {_format_deps(pins)}" for name, pins in extras.items())


def _scripts_lines(scripts: dict[str, str]) -> str:
    return "\n".join(f"- `{name}` → `{target}`" for name, target in scripts.items())


def _parse_omegaprompt_pin(deps: list[str]) -> str:
    for d in deps:
        if d.startswith("omegaprompt"):
            return d
    return ""


def _badge_version(version: str) -> str:
    # Used by check_repo_consistency to compare README badge text.
    return version


# ---------------------------------------------------------------------------
# Render — English
# ---------------------------------------------------------------------------


